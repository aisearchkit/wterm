// 把 wterm 源码打成 dist/wterm.js(+.map) 和 dist/wterm.css
// 用法: WTERM_SRC=<wterm 源码根目录> node build.mjs [--minify]
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.env.WTERM_SRC || join(here, ".."));
const W = join(src, "packages/@wterm");
const dist = join(here, "dist");
const minify = process.argv.includes("--minify");
mkdirSync(dist, { recursive: true });

// 1) wasm -> base64 -> core/src/wasm-inline.ts（等价于上游 core 的 prebuild: inline-wasm.js）
const wasm = readFileSync(join(W, "core/wasm/wterm.wasm"));
writeFileSync(
  join(W, "core/src/wasm-inline.ts"),
  `// Auto-generated by bundle/build.mjs\nexport const WASM_BASE64 = "${wasm.toString("base64")}";\n`,
);

// 2) esbuild：@wterm/core、@wterm/dom 直接指向 TS 源码（不走 npm 包、不走 tsc）
await build({
  entryPoints: [join(here, "entry.ts")],
  outfile: join(dist, "wterm.js"),
  bundle: true,
  format: "iife",
  globalName: "WTermLib",
  platform: "browser",
  target: "es2020",
  minify,
  sourcemap: "linked",
  legalComments: "none",
  tsconfigRaw: "{}", // 不读上游 tsconfig（它 extends 了 workspace 包）
  alias: {
    "@wterm/core": join(W, "core/src/index.ts"),
    "@wterm/dom": join(W, "dom/src/index.ts"),
  },
  logLevel: "info",
});

// 3) CSS 原样复制
copyFileSync(join(W, "dom/src/terminal.css"), join(dist, "wterm.css"));
copyFileSync(join(src, "LICENSE"), join(dist, "WTERM-LICENSE.txt"));

const ver = JSON.parse(readFileSync(join(W, "core/package.json"), "utf8")).version;
writeFileSync(join(dist, "VERSION.txt"), `wterm ${ver}\n`);
for (const f of ["wterm.js", "wterm.js.map", "wterm.css"])
  console.log(f.padEnd(14), statSync(join(dist, f)).size, "bytes");
